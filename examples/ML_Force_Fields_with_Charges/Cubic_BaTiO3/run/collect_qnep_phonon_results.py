"""Collect GPUMD qNEP dump_bec outputs into a Phonopy NAC archive.

This is a small, calculator-neutral bridge for the compatibility example. It
does not train qNEP and does not run GPU jobs.  The three force-displacement
folders are expected to have been generated from the same ``phonopy_disp.yaml``
as the DFT baseline.  ``dump_bec.xyz`` is parsed from its final frame; BECs are
averaged over the symmetry-equivalent atoms in the 40-atom archive and written
in primitive-cell order.
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path
import shutil

import numpy as np
from phonopy import load


def _last_dump(path: Path) -> tuple[np.ndarray, np.ndarray]:
    lines = path.read_text(encoding="utf-8").splitlines()
    cursor = 0
    frames: list[list[list[str]]] = []
    while cursor < len(lines):
        if not lines[cursor].strip():
            cursor += 1
            continue
        natoms = int(lines[cursor])
        frames.append([line.split() for line in lines[cursor + 2:cursor + 2 + natoms]])
        cursor += natoms + 2
    if not frames:
        raise ValueError(f"No frames found in {path}")
    atoms = frames[-1]
    if any(len(row) < 16 for row in atoms):
        raise ValueError(f"dump_bec.xyz lacks bec/forces columns: {path}")
    bec = np.asarray([[float(x) for x in row[4:13]] for row in atoms], dtype=float).reshape(-1, 3, 3)
    forces = np.asarray([[float(x) for x in row[13:16]] for row in atoms], dtype=float)
    return bec, forces


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--phonopy-yaml", required=True)
    parser.add_argument("--dump-root", required=True, help="folder containing disp-001/... and no-move/")
    parser.add_argument("--output", required=True)
    parser.add_argument("--sqrt-epsilon-infinity", type=float, required=True)
    parser.add_argument("--model", required=True)
    args = parser.parse_args()

    source = Path(args.phonopy_yaml).resolve()
    dumps = Path(args.dump_root).resolve()
    target = Path(args.output).resolve()
    target.mkdir(parents=True, exist_ok=True)
    phonon = load(phonopy_yaml=str(source), produce_fc=False)
    if len(phonon.supercell) != 40 or len(phonon.primitive) != 5:
        raise ValueError("The example collector expects the 40-atom/5-atom cubic-BTO archive")

    force_sets = target / "FORCE_SETS"
    with force_sets.open("w", encoding="utf-8", newline="\n") as handle:
        handle.write(f"{len(phonon.supercell)}\n\n{len(phonon.displacements)}\n")
        for index, displacement in enumerate(phonon.displacements, start=1):
            _bec, forces = _last_dump(dumps / f"disp-{index:03d}" / "dump_bec.xyz")
            handle.write(f"{int(displacement[0]) + 1}\n")
            handle.write(" ".join(f"{value:.16g}" for value in displacement[1:]) + "\n")
            for row in forces:
                handle.write(" ".join(f"{value:.16g}" for value in row) + "\n")

    bec, _ = _last_dump(dumps / "no-move" / "dump_bec.xyz")
    # Phonopy's BORN file stores symmetry-independent primitive atoms only for
    # this cubic archive: Ba, Ti, and one O representative. The other two O
    # tensors are generated by the primitive-cell symmetry operations.
    primitive_bec = [bec[offset:offset + 8].mean(axis=0) for offset in (0, 8, 16)]
    epsilon = float(args.sqrt_epsilon_infinity) ** 2
    with (target / "BORN").open("w", encoding="utf-8", newline="\n") as handle:
        handle.write("# qNEP GPUMD dump_bec; row-major field/coordinate convention\n")
        handle.write(" ".join(f"{epsilon if i in (0, 4, 8) else 0.0:.12g}" for i in range(9)) + "\n")
        for tensor in primitive_bec:
            handle.write(" ".join(f"{value:.12g}" for value in tensor.reshape(-1)) + "\n")

    shutil.copy2(source, target / "phonopy.yaml")
    disp = source.with_name("phonopy_disp.yaml")
    if disp.is_file():
        shutil.copy2(disp, target / "phonopy_disp.yaml")
    manifest = {
        "schema": "zstar-qnep-phonon-results",
        "model": args.model,
        "sqrt_epsilon_infinity": float(args.sqrt_epsilon_infinity),
        "epsilon_infinity": epsilon,
        "force_constant_source": "GPUMD qNEP dump_bec.xyz",
        "bec_source": "GPUMD qNEP no-move dump_bec.xyz",
        "supercell_atoms": len(phonon.supercell),
        "primitive_atoms": len(phonon.primitive),
        "nac_protocol": "Phonopy NAC using qNEP BEC and electronic dielectric scalar",
    }
    (target / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
